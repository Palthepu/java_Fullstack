package com.operators;

public class BitwiseOperators {

	public static void main(String[] args) {
		int a=50;
		int b=40;
		System.out.println(a & b);
		System.out.println(a|b);
		System.out.println(a^b);
		System.out.println(~b);
		System.out.println(a<<b);
		System.out.println(a>>b);
		System.out.println(a>>>b);
	}

}
