package com.operators;

public class RelationalOperators {

	public static void main(String[] args) {
		float a=23.4f;
		float b=25.4f;
		System.out.println(a==b);
		System.out.println(a!=b);
		System.out.println(a>b);
		System.out.println(a<b);
		System.out.println(a>=b);
		System.out.println(a<=b);
	}

}
